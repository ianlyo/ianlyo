/** Recursively normalize literal strings/arrays to structural types so locale key drift fails `astro check`. */
type LocaleShape<T> = T extends readonly string[]
  ? readonly string[]
  : T extends Record<string, unknown>
    ? { readonly [K in keyof T]: LocaleShape<T[K]> }
    : string;

type AssertTrue<T extends true> = T;
type AssertExactShape<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false;
export type LocaleParityCheck = AssertTrue<
  AssertExactShape<LocaleShape<(typeof ui)['zh-Hant']>, LocaleShape<(typeof ui)['en']>>
>;

export function t(lang: Lang) {
  return ui[lang];
}

/** Prefix a path with the language. zh-Hant is the default (no prefix). */
export function localePath(lang: Lang, path: string) {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return lang === 'en' ? `/en${clean}` : clean;
}

